import 'dart:math';

/// 时间名言警句池:四环仪弹窗底部每次随机展示一句。
///
/// 文案口径:短句 + 出处,控制在两行以内;末两条为与 App
/// 「当下即防线」气质呼应的原创句,不带出处。
const kTimeQuotes = <String>[
  '逝者如斯夫,不舍昼夜。—— 《论语》',
  '盛年不重来,一日难再晨。及时当勉励,岁月不待人。—— 陶渊明',
  '我生待明日,万事成蹉跎。—— 《明日歌》',
  '莫等闲,白了少年头,空悲切。—— 岳飞',
  '一寸光阴一寸金,寸金难买寸光阴。—— 《增广贤文》',
  '少壮不努力,老大徒伤悲。—— 《长歌行》',
  '时间就是生命,无端空耗时间,无异于谋财害命。—— 鲁迅',
  '时间是组成生命的材料。—— 富兰克林',
  '昨天是作废的支票,明天是期票,只有今天才是现金。—— 富兰克林',
  '时间是伟大的作者,她能写出未来的结局。—— 卓别林',
  '合理利用时间就等于节约时间。—— 培根',
  '放弃时间的人,时间也会放弃他。—— 莎士比亚',
  '把每一个当下过好,一生便自然被过好。',
  '此刻,是过去所有时刻的收成,也是未来所有时刻的种子。',
];

/// 从池中随机抽取一句([rng] 可注入,便于测试与回放)。
String pickTimeQuote([Random? rng]) {
  final r = rng ?? Random();
  return kTimeQuotes[r.nextInt(kTimeQuotes.length)];
}
